import { strFromU8, strToU8, unzipSync, zipSync, type Zippable } from "fflate/browser";
import { addNativeCellImages, type NativeCellImage } from "./native-cell-images.js";
import { writeDefinedNames } from "./defined-names.js";
import { writeWorkbookCalculationSettings } from "./workbook-calculation.js";
import {
  writeXlsxDataMetadata,
  writeXlsxFilterColorFormats,
  type XlsxDataMetadata,
} from "./data-tools-metadata.js";
import { writeXlsxConditionalFormats } from "./conditional-formatting.js";
import { writeXlsxTableMetadata } from "./table-styles.js";
import { writeXlsxCellStyles, writeXlsxNamedCellStyleBindings } from "./cell-styles.js";
import { writeXlsxThemeStyleBindings } from "./theme-style-bindings.js";
import { writeXlsxHyperlinks } from "./hyperlinks.js";
import { writeXlsxCellNoteVmlBoxes, writeXlsxCellNotes } from "./cell-notes.js";
import { writeXlsxPageSetups } from "./page-setup.js";
import type { CompatibilityReportBuilder } from "./report.js";
import type { Sheet, WorkbookCalculationSettings } from "@idea10/core/workbook";
import type { SheetConditionalFormatRule } from "@idea10/core/conditional-formatting";
import type { TableStyleDefinition } from "@idea10/core/table-styles";
import type { PivotTableStyleDefinition } from "@idea10/core/pivot-table-styles";
import type { CellStyleDefinition } from "@idea10/core/cell-styles";
import type { SheetPageSetup } from "@idea10/core/page-setup";
import { resolveThemeFont, type WorkbookTheme } from "@idea10/core/workbook-theme";
import { writeXlsxWorkbookTheme } from "./workbook-theme.js";

/** Finalize only archives just generated by this adapter, never imported files. */
export function finalizeXlsxExport(
  bytes: Uint8Array,
  cellImages: readonly NativeCellImage[],
  definedNames: readonly {
    name: string;
    localSheetId?: number;
    reference: string;
  }[] = [],
  calculation?: WorkbookCalculationSettings,
  dataMetadata: readonly Omit<
    XlsxDataMetadata,
    "unsupportedFilters" | "unsupportedValidations"
  >[] = [],
  conditionalFormats: readonly SheetConditionalFormatRule[][] = [],
  sheets: readonly Sheet[] = [],
  tableStyles: readonly TableStyleDefinition[] = [],
  defaultTableStyleId?: string,
  pivotTableStyles: readonly PivotTableStyleDefinition[] = [],
  defaultPivotTableStyleId?: string,
  cellStyles?: readonly CellStyleDefinition[],
  pageSetups: readonly (SheetPageSetup | undefined)[] = [],
  theme?: WorkbookTheme,
  report?: CompatibilityReportBuilder,
  sheetBackgrounds: readonly (string | undefined)[] = [],
  structureProtected = false,
): Uint8Array {
  const entries = unzipSync(bytes);
  const styles = entries["xl/styles.xml"];
  if (!styles) throw new Error("Missing generated XLSX styles.");
  // ExcelJS assigns Normal to its first font, Calibri 11 + the locale-dependent
  // minor theme. Column-width conversion requires an explicit, unthemed font.
  let normalized = false;
  const fixedStyles = strFromU8(styles).replace(/<font>.*?<\/font>/s, (font) => {
    if (!font.includes('<name val="Calibri"/>') || !font.includes('<sz val="11"/>'))
      throw new Error("Unexpected generated XLSX Normal font.");
    normalized = true;
    return font.replace(/<scheme\b[^>]*\/>/g, "");
  });
  if (!normalized) throw new Error("Missing generated XLSX Normal font.");
  entries["xl/styles.xml"] = strToU8(fixedStyles);
  for (const [name, content] of Object.entries(entries)) {
    if (!/^xl\/drawings\/drawing\d+\.xml$/.test(name)) continue;
    // editAs belongs to twoCellAnchor only; ExcelJS 4.4 writes it on both kinds.
    entries[name] = strToU8(
      strFromU8(content).replace(/<xdr:oneCellAnchor\s+editAs="[^"]*">/g, "<xdr:oneCellAnchor>"),
    );
  }
  addNativeCellImages(entries, cellImages);
  writeDefinedNames(entries, definedNames);
  writeXlsxDataMetadata(entries, dataMetadata);
  writeXlsxPageSetups(entries, pageSetups, report);
  writeXlsxConditionalFormats(entries, conditionalFormats, report);
  writeXlsxTableMetadata(
    entries,
    sheets,
    tableStyles,
    defaultTableStyleId,
    pivotTableStyles,
    defaultPivotTableStyleId,
  );
  writeXlsxFilterColorFormats(
    entries,
    sheets as unknown as Parameters<typeof writeXlsxFilterColorFormats>[1],
  );
  writeXlsxHyperlinks(entries, sheets);
  writeXlsxCellNotes(entries, sheets);
  writeXlsxProtection(entries, sheets, structureProtected);
  writeXlsxCellNoteVmlBoxes(entries, sheets);
  const projectedCellStyles = cellStyles?.map((definition) => ({
    ...definition,
    style:
      definition.style.fontTheme && theme
        ? {
            ...definition.style,
            fontFamily: resolveThemeFont(theme, definition.style.fontTheme),
          }
        : definition.style,
  }));
  entries["xl/styles.xml"] = strToU8(
    writeXlsxCellStyles(strFromU8(entries["xl/styles.xml"]!), projectedCellStyles),
  );
  writeXlsxNamedCellStyleBindings(entries, sheets, cellStyles);
  writeXlsxThemeStyleBindings(entries, sheets, theme);
  for (const [index, mediaFilename] of sheetBackgrounds.entries()) {
    if (!mediaFilename) continue;
    const sheetName = `xl/worksheets/sheet${index + 1}.xml`;
    const sheet = entries[sheetName];
    if (!sheet) continue;
    const relName = `xl/worksheets/_rels/sheet${index + 1}.xml.rels`;
    const rels = entries[relName]
      ? strFromU8(entries[relName])
      : '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"/>';
    const ids = [...rels.matchAll(/\bId="rId(\d+)"/g)].map((match) => Number(match[1]));
    const id = `rId${Math.max(0, ...ids) + 1}`;
    const relationship = `<Relationship Id="${id}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="../media/${mediaFilename.split("/").at(-1)}"/>`;
    entries[relName] = strToU8(
      /<Relationships\b[^>]*\/>$/.test(rels)
        ? rels.replace(/\/>$/, `>${relationship}</Relationships>`)
        : rels.replace(/<\/Relationships>$/, `${relationship}</Relationships>`),
    );
    const xml = strFromU8(sheet).replace(/<picture\b[^>]*\/>/g, "");
    entries[sheetName] = strToU8(
      xml.replace(
        /<(?:oleObjects|controls|webPublishItems|tableParts|extLst)\b|<\/worksheet>/,
        (next) => `<picture r:id="${id}"/>${next}`,
      ),
    );
  }
  if (calculation) writeWorkbookCalculationSettings(entries, calculation);
  if (theme) writeXlsxWorkbookTheme(entries, theme);
  const files: Zippable = {};
  for (const [name, content] of Object.entries(entries)) {
    if (name.endsWith("/")) continue;
    // Image payloads are already compressed; do not compress them a second time.
    files[name] = [content, { level: name.startsWith("xl/media/") ? 0 : 6 }];
  }
  return zipSync(files);
}
