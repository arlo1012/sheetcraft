const LOCALE_BY_LCID = new Map<string, NumberFormatLocale>(
  NUMBER_FORMAT_LOCALES.map((entry) => [entry.lcid, entry]),
);

const LOCALE_BY_TAG = new Map<string, NumberFormatLocale>();
for (const entry of NUMBER_FORMAT_LOCALES) {
  LOCALE_BY_TAG.set(normalizeLocaleKey(entry.locale), entry);
  try {
    // Microsoft retains several legacy language and region tags. Also index
    // their Intl canonical form so callers can use either spelling.
    LOCALE_BY_TAG.set(
      normalizeLocaleKey(Intl.getCanonicalLocales(entry.locale)[0] ?? entry.locale),
      entry,
    );
  } catch {
    // Every static entry was validated when generated; retain this guard for
    // runtimes with a smaller Intl locale implementation.
  }
}

/** Returns the Microsoft LCID as uppercase hexadecimal without a 0x prefix or padding. */
export function getNumberFormatLocaleId(locale: string): string | undefined {
  return findNumberFormatLocale(locale)?.lcid;
}

/** Accepts a padded or unpadded hexadecimal LCID and returns its Microsoft locale spelling. */
export function getNumberFormatLocale(lcid: string): string | undefined {
  return LOCALE_BY_LCID.get(normalizeLcid(lcid))?.locale;
}

/** Returns the current CLDR tender currency for a known locale, when present. */
export function getNumberFormatLocaleCurrency(locale: string): string | undefined {
  return findNumberFormatLocale(locale)?.currency;
}

function findNumberFormatLocale(locale: string): NumberFormatLocale | undefined {
  if (typeof locale !== "string") return undefined;
  const key = normalizeLocaleKey(locale);
  if (!key) return undefined;
  return LOCALE_BY_TAG.get(key);
}

function normalizeLocaleKey(locale: string): string {
  return locale.trim().replaceAll("_", "-").toLowerCase();
}

function normalizeLcid(lcid: string): string {
  if (typeof lcid !== "string") return "";
  const value = lcid.trim().replace(/^0x/i, "").toUpperCase();
  return /^[0-9A-F]+$/.test(value) ? value.replace(/^0+(?=[0-9A-F])/, "") : "";
}
