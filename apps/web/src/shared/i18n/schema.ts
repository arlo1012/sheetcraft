type LeafPath<T> = {
  [Key in keyof T & string]: T[Key] extends string
    ? Key
    : T[Key] extends Record<string, unknown>
      ? `${Key}.${LeafPath<T[Key]>}`
      : never;
}[keyof T & string];

export type MessageKey = LeafPath<MessageSchema>;
