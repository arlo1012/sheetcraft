import { mount, flushPromises, type VueWrapper } from "@vue/test-utils";
import { afterEach, expect, test, vi } from "vitest";
import { Select } from "tdesign-vue-next/es/select";
import { BmpImageSourceError } from "../../../../modules/image-assets/inspectBmpImageHeader";
import { createAppI18n } from "../../../../shared/i18n";
import PicturePaintEditor from "../../../../modules/sheet-images/components/format-pane/PicturePaintEditor.vue";
import PictureTextureGallery from "../../../../modules/sheet-images/components/format-pane/PictureTextureGallery.vue";
import type { Choice, PicturePaint } from "@sheetcraft/core/picture-detailed-style";
const encode = vi.hoisted(() =>
  vi.fn(async () => new Blob(["product-owned texture"], { type: "image/png" })),
);
vi.mock("../../../../modules/sheet-images/picture-texture", async (importActual) => ({
  ...(await importActual<object>()),
  createPictureTextureBlob: encode,
}));
const wrappers: VueWrapper[] = [];
afterEach(() => {
  wrappers.splice(0).forEach((wrapper) => wrapper.unmount());
  encode.mockClear();
});
function value(): Choice<PicturePaint> {
  return {
    kind: "value",
    value: {
      kind: "picture",
      assetId: "old",
      opacity: 0.37,
      rotateWithShape: false,
      layout: {
        kind: "tile",
        scaleX: 2,
        scaleY: 3,
        offsetXPt: 4,
        offsetYPt: 5,
        anchor: "top-right",
        flip: "xy",
      },
    },
  };
}
function create() {
  let resolve!: (id: string) => void;
  const loadAsset = vi.fn(
      () =>
        new Promise<string>((r) => {
          resolve = r;
        }),
    ),
    onCommit = vi.fn(() => true);
  const wrapper = mount(PicturePaintEditor, {
    props: {
      ownerKey: "owner",
      value: value(),
      t: (key) => key,
      sourceAssetId: "photo",
      loadAsset,
      onCommit,
    },
    global: {
      plugins: [createAppI18n("en-US")],
      stubs: { PictureTextureGallery: true, ColorPaletteSelect: true },
    },
  });
  wrappers.push(wrapper);
  return { wrapper, loadAsset, onCommit, resolve: (id: string) => resolve(id) };
}
test("a preset uses actual generated bytes and retains the existing tile geometry and transparency", async () => {
  const f = create();
  f.wrapper.getComponent(PictureTextureGallery).props("onSelect")("denim");
  await flushPromises();
  expect(encode).toHaveBeenCalledExactlyOnceWith("denim");
  expect(f.loadAsset).toHaveBeenCalledWith(expect.any(Blob), "denim");
  f.resolve(`image-texture-v1-denim-${"b".repeat(64)}`);
  await flushPromises();
  const old = value();
  if (old.kind !== "value") throw Error("Bad test fixture.");
  expect(f.onCommit).toHaveBeenCalledExactlyOnceWith({
    kind: "value",
    value: { ...old.value, assetId: `image-texture-v1-denim-${"b".repeat(64)}` },
  });
});
test.each(["owner", "callback", "paint", "disabled", "unmount"] as const)(
  "late texture bytes cannot change the target after %s",
  async (boundary) => {
    const f = create();
    f.wrapper.getComponent(PictureTextureGallery).props("onSelect")("paper");
    await flushPromises();
    if (boundary === "owner") await f.wrapper.setProps({ ownerKey: "next" });
    if (boundary === "callback") await f.wrapper.setProps({ onCommit: vi.fn(() => true) });
    if (boundary === "paint") await f.wrapper.setProps({ value: { kind: "none" } });
    if (boundary === "disabled") await f.wrapper.setProps({ disabled: true });
    if (boundary === "unmount") f.wrapper.unmount();
    f.resolve("late");
    await flushPromises();
    expect(f.onCommit).not.toHaveBeenCalled();
    if (boundary === "callback") expect(f.wrapper.props("onCommit")).not.toHaveBeenCalled();
  },
);
test("switching to picture fill chooses an own texture instead of repeating the source photograph", async () => {
  const f = create();
  await f.wrapper.setProps({ value: { kind: "none" } });
  f.wrapper
    .findAllComponents(Select)
    .find((c) => c.attributes("aria-label") === "paintMode")!
    .vm.$emit("change", "picture");
  await flushPromises();
  expect(encode).toHaveBeenCalledWith("paper");
  expect(f.onCommit).not.toHaveBeenCalled();
  f.resolve("new-texture");
  await flushPromises();
  expect(f.onCommit).toHaveBeenCalledExactlyOnceWith({
    kind: "value",
    value: {
      kind: "picture",
      assetId: "new-texture",
      opacity: 1,
      rotateWithShape: true,
      layout: {
        kind: "tile",
        scaleX: 1,
        scaleY: 1,
        offsetXPt: 0,
        offsetYPt: 0,
        anchor: "center",
        flip: "none",
      },
    },
  });
});
test("file paint replacement keeps its stretch offsets and rejects unavailable storage without editing", async () => {
  const f = create(),
    stretch: Choice<PicturePaint> = {
      kind: "value",
      value: {
        kind: "picture",
        assetId: "old",
        opacity: 0.5,
        rotateWithShape: false,
        layout: {
          kind: "stretch",
          offsetXRatio: -0.2,
          offsetYRatio: 0.1,
          widthRatio: 1.3,
          heightRatio: 0.8,
        },
      },
    };
  await f.wrapper.setProps({ value: stretch });
  const input = f.wrapper.get<HTMLInputElement>('input[type="file"]');
  Object.defineProperty(input.element, "files", {
    value: [new File(["synthetic"], "test.png", { type: "image/png" })],
    configurable: true,
  });
  await input.trigger("change");
  await flushPromises();
  f.resolve("replacement");
  await flushPromises();
  expect(f.onCommit).toHaveBeenLastCalledWith({
    kind: "value",
    value: { ...stretch.value, assetId: "replacement" },
  });
  f.onCommit.mockClear();
  await input.trigger("change");
  await flushPromises();
  f.resolve("");
  await flushPromises();
  expect(f.onCommit).not.toHaveBeenCalled();
  expect(f.wrapper.text()).toContain("applyRejected");
});

test("source-format chooser includes BMP/SVG and rejected bytes explain a usable alternative", async () => {
  const f = create();
  const accept = f.wrapper.get('input[type="file"]').attributes("accept");
  expect(accept).toContain(".bmp");
  expect(accept).toContain(".svg");
  await f.wrapper.setProps({
    loadAsset: vi.fn(async () => {
      throw new BmpImageSourceError("unsupported-feature");
    }),
  });
  f.wrapper.getComponent(PictureTextureGallery).props("onSelect")("paper");
  await flushPromises();
  expect(f.wrapper.text()).toContain("This BMP encoding or color profile is not supported.");
  expect(f.onCommit).not.toHaveBeenCalled();
});

test("late source validation errors do not replace a new paint selection's feedback", async () => {
  const f = create();
  let reject!: (error: unknown) => void;
  await f.wrapper.setProps({
    loadAsset: () =>
      new Promise<string>((_resolve, failure) => {
        reject = failure;
      }),
  });
  f.wrapper.getComponent(PictureTextureGallery).props("onSelect")("paper");
  await flushPromises();
  await f.wrapper.setProps({ value: { kind: "none" } });
  reject(new BmpImageSourceError("unsupported-feature"));
  await flushPromises();
  expect(f.wrapper.text()).not.toContain("This BMP encoding");
  expect(f.onCommit).not.toHaveBeenCalled();
});
